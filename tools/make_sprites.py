#!/usr/bin/env python3
"""Bake assets/*.png into src/sprites.h (needs Pillow). Run from anywhere."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
FARMER_FRAME = (16, 18)              # sheet: 3 columns (stand, step, step) x 4 rows
FARMER_SCALE = 3
# tiles used from the 12-column, 16 px sheet; the order is what potato.c indexes
FIELD_TILES = [48, 49, 50,                      # soil row: left end, middle, right end
               15, 27, 39, 78, 83, 3, 77]       # tree, tree, bush, berries, sunflower, sapling, rocks
BOMB_WS = [                          # per size (small, medium, big): pulse frames
    [24, 26, 28, 30, 32, 34],
    [36, 38, 40, 42, 44, 46],
    [50, 52, 54, 56, 58, 60],
]


def bake(name, im):
    width, height = im.size
    data = im.tobytes()
    rows = (",".join(map(str, data[i:i + 24])) for i in range(0, len(data), 24))
    body = ",\n    ".join(rows)
    code = f"static const uint8_t {name}_px[] = {{\n    {body}\n}};\n"
    return code, f"{{ {width}, {height}, {name}_px }}"


def photo(src, width):
    # resize with premultiplied alpha so the transparent border leaves no halo
    im = Image.open(src).convert("RGBA").convert("RGBa")
    height = round(im.height * width / im.width)
    return im.resize((width, height), Image.LANCZOS).convert("RGBA")


def array(name, entries):
    return (f"static const sprite_t {name}[{len(entries)}] = {{\n    "
            + ",\n    ".join(entries) + "\n};")


def main():
    out = [
        "/* Generated by tools/make_sprites.py from assets/ - do not edit. */",
        "#include <stdint.h>\n",
        "typedef struct { int w, h; const uint8_t *px; } sprite_t;  /* RGBA */\n",
    ]
    sheet = Image.open(ROOT / "assets/farmer.png").convert("RGBA")
    fw, fh = FARMER_FRAME
    if sheet.size != (fw * 3, fh * 4):
        raise SystemExit(f"farmer.png must be {fw * 3}x{fh * 4}, got {sheet.size}")
    farmer = []
    for row in range(4):
        for col in range(3):
            frame = sheet.crop((col * fw, row * fh, (col + 1) * fw, (row + 1) * fh))
            frame = frame.resize((fw * FARMER_SCALE, fh * FARMER_SCALE), Image.NEAREST)
            code, entry = bake(f"farmer{row}{col}", frame)
            out.append(code)
            farmer.append(entry)
    tiles = Image.open(ROOT / "assets/field_tiles.png").convert("RGBA")
    if tiles.size != (12 * 16, 11 * 16):
        raise SystemExit(f"field_tiles.png must be 192x176, got {tiles.size}")
    field = []
    for n in FIELD_TILES:
        x, y = n % 12 * 16, n // 12 * 16
        tile = tiles.crop((x, y, x + 16, y + 16)).resize((32, 32), Image.NEAREST)
        code, entry = bake(f"tile{n}", tile)
        out.append(code)
        field.append(entry)
    sizes = []
    for size, widths in enumerate(BOMB_WS):
        row = []
        for i, w in enumerate(widths):
            code, entry = bake(f"bomb{size}_{i}", photo(ROOT / "assets/potato_bomb.png", w))
            out.append(code)
            row.append(entry)
        sizes.append("{ " + ",\n      ".join(row) + " }")
    out.append(array("FARMER_SPR", farmer) + "   /* [row * 3 + col] */")
    out.append(array("TILE_SPR", field))
    out.append(f"#define BOMB_SIZES {len(BOMB_WS)}")
    out.append(f"#define BOMB_FRAMES {len(BOMB_WS[0])}")
    out.append("static const sprite_t BOMB_SPR[BOMB_SIZES][BOMB_FRAMES] = {\n    "
               + ",\n    ".join(sizes) + "\n};")
    (ROOT / "src/sprites.h").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
